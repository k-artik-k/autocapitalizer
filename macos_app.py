"""macOS backend for WhatsApp Capitalise.

This listens for keyboard events only after macOS Accessibility permission is
granted. It only modifies text while WhatsApp Desktop, or a browser tab whose
title is WhatsApp, is frontmost. No typed text is written to disk.
"""
import fcntl
import os
import subprocess
import sys
import threading

import pystray
from AppKit import NSWorkspace
from PIL import Image, ImageDraw
import Quartz

import autocorrect
import settings as settings_store
from sentence_engine import Typist, VK_BACK, VK_RETURN


DEBUG = "--debug" in sys.argv
APP_NAME = "WhatsAppCapitalize"
TRAY_TITLE = "WhatsApp Capitalise"
DATA_DIR = os.path.join(os.path.expanduser("~/Library/Application Support"), APP_NAME)
SETTINGS_PATH = os.path.join(DATA_DIR, "settings.json")
CORRECTIONS_PATH = os.path.join(DATA_DIR, "my_corrections.txt")
LOCK_PATH = os.path.join(DATA_DIR, "app.lock")

# WhatsApp Desktop and the browsers that can host WhatsApp Web on macOS.
WHATSAPP_BUNDLE_IDS = {"net.whatsapp.WhatsApp"}
BROWSER_BUNDLE_IDS = {
    "com.apple.Safari",
    "com.google.Chrome",
    "com.microsoft.edgemac",
    "org.mozilla.firefox",
    "com.brave.Browser",
    "com.operasoftware.Opera",
    "com.vivaldi.Vivaldi",
}

# macOS virtual key codes normalized to the Windows-style values understood by
# the platform-neutral sentence engine. Other keys only need their character.
MAC_BACKSPACE = 51
MAC_RETURN = 36
MAC_KEY_F11 = 103
MAC_KEY_F12 = 111
MAC_TO_ENGINE_KEY = {
    48: 0x09,    # Tab
    53: 0x1B,    # Escape
    116: 0x21,   # Page Up
    121: 0x22,   # Page Down
    119: 0x23,   # End
    115: 0x24,   # Home
    123: 0x25,   # Left arrow
    126: 0x26,   # Up arrow
    124: 0x27,   # Right arrow
    125: 0x28,   # Down arrow
    117: 0x2E,   # Forward delete
    MAC_BACKSPACE: VK_BACK,
    MAC_RETURN: VK_RETURN,
}
ENGINE_TO_MAC_KEY = {VK_BACK: MAC_BACKSPACE, VK_RETURN: MAC_RETURN}

# Marks keyboard events generated by this app. The event callback lets these
# through unchanged, preventing the injected text from being processed twice.
MAGIC = 0x57414341

typist = Typist()
tray = None
enabled = True
hook_ok = False
in_target = False
permission_required = False
settings = dict(settings_store.DEFAULTS)
swallowed = set()
_event_tap = None
_event_source = None
_hook_run_loop = None
_lock_handle = None


def web_title_ok(title):
    """Accept WhatsApp browser tabs, but not arbitrary pages mentioning it."""
    title = (title or "").strip()
    if title.startswith("(") and ")" in title:
        closing = title.find(")")
        if title[1:closing].isdigit():
            title = title[closing + 1:].lstrip()
    lowered = title.lower()
    if not lowered.startswith("whatsapp"):
        return False
    rest = lowered[len("whatsapp"):]
    return rest == "" or rest.startswith((" - ", " — ", " – ", " and ", " | "))


def frontmost_app():
    try:
        return NSWorkspace.sharedWorkspace().frontmostApplication()
    except Exception:
        return None


def window_title_for_pid(pid):
    """Return the frontmost standard window title owned by *pid*, if present."""
    try:
        options = Quartz.kCGWindowListOptionOnScreenOnly | Quartz.kCGWindowListExcludeDesktopElements
        windows = Quartz.CGWindowListCopyWindowInfo(options, Quartz.kCGNullWindowID) or ()
        for window in windows:
            if window.get(Quartz.kCGWindowOwnerPID) != pid:
                continue
            if window.get(Quartz.kCGWindowLayer, 0) != 0:
                continue
            title = window.get(Quartz.kCGWindowName, "")
            if title:
                return str(title)
    except Exception:
        pass
    return ""


def foreground_info():
    app = frontmost_app()
    if app is None:
        return "", ""
    bundle_id = str(app.bundleIdentifier() or "")
    title = window_title_for_pid(app.processIdentifier()) if bundle_id in BROWSER_BUNDLE_IDS else ""
    if DEBUG:
        print(f"[focus] bundle={bundle_id!r} title={title[:80]!r} target={is_target(bundle_id, title)}")
    return bundle_id, title


def is_target(bundle_id, title):
    return bundle_id in WHATSAPP_BUNDLE_IDS or (
        bundle_id in BROWSER_BUNDLE_IDS and web_title_ok(title)
    )


def make_icon(state="on", size=64):
    """Draw the same green/grey/red status icon used by the Windows build."""
    source_size = 256
    image = Image.new("RGBA", (source_size, source_size), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    colour = {"on": (37, 211, 102), "paused": (120, 124, 130), "error": (222, 62, 62)}[state]
    white = (255, 255, 255, 255)
    draw.rounded_rectangle((8, 8, source_size - 8, source_size - 8), radius=56, fill=colour + (255,))
    if state == "on":
        draw.line([(62, 200), (128, 56), (194, 200)], fill=white, width=30, joint="curve")
        draw.line([(88, 152), (168, 152)], fill=white, width=24)
    elif state == "paused":
        draw.rectangle((84, 64, 116, 192), fill=white)
        draw.rectangle((140, 64, 172, 192), fill=white)
    else:
        draw.rounded_rectangle((112, 56, 144, 150), radius=14, fill=white)
        draw.ellipse((108, 172, 148, 212), fill=white)
    return image.resize((size, size), Image.LANCZOS)


def tray_state():
    if not hook_ok:
        return "error"
    return "on" if enabled else "paused"


def status_text(_item=None):
    if permission_required:
        return "Accessibility permission required"
    if not hook_ok:
        return "Keyboard listener not running"
    if not enabled:
        return "Paused"
    return "Active in WhatsApp" if in_target else "On - waiting for WhatsApp"


def refresh_tray():
    if not tray:
        return
    try:
        tray.icon = make_icon(tray_state())
        tray.title = f"{TRAY_TITLE} - {status_text()}"
        tray.update_menu()
    except Exception as exc:
        if DEBUG:
            print("tray refresh failed:", exc)


def notify(message):
    try:
        if tray:
            tray.notify(message, TRAY_TITLE)
    except Exception:
        pass


def _save_settings():
    try:
        os.makedirs(DATA_DIR, exist_ok=True)
        settings_store.save(SETTINGS_PATH, settings)
    except OSError as exc:
        if DEBUG:
            print("could not save settings:", exc)


def set_enabled(value):
    global enabled
    enabled = value
    if not enabled:
        leave_target()
    refresh_tray()


def toggle_enabled(*_):
    set_enabled(not enabled)


def toggle_capitalize(*_):
    settings["capitalize"] = not settings["capitalize"]
    typist.capitalize = settings["capitalize"]
    _save_settings()
    refresh_tray()


def toggle_fix_words(*_):
    settings["fix_words"] = not settings["fix_words"]
    typist.fix_words = settings["fix_words"]
    _save_settings()
    refresh_tray()


def open_corrections(*_):
    os.makedirs(DATA_DIR, exist_ok=True)
    if not os.path.exists(CORRECTIONS_PATH):
        with open(CORRECTIONS_PATH, "w", encoding="utf-8") as file:
            file.write("# One per line:   what you type = what it becomes\n"
                       "# Save the file and it works immediately (no restart).\n"
                       "# omw = on my way\n"
                       "# ill = I'll\n")
    subprocess.Popen(["open", CORRECTIONS_PATH])


def open_data_folder(*_):
    os.makedirs(DATA_DIR, exist_ok=True)
    subprocess.Popen(["open", DATA_DIR])


def open_accessibility_settings(*_):
    subprocess.Popen([
        "open",
        "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility",
    ])


def _is_accessibility_trusted(prompt=False):
    try:
        if prompt:
            Quartz.AXIsProcessTrustedWithOptions({Quartz.kAXTrustedCheckOptionPrompt: True})
        return bool(Quartz.AXIsProcessTrusted())
    except (AttributeError, TypeError):
        # Event-tap creation below remains the definitive availability check.
        return True


def leave_target():
    global in_target
    if in_target:
        typist.lose_track()
        in_target = False
        threading.Thread(target=refresh_tray, daemon=True).start()


def normalize_key(key_code):
    return MAC_TO_ENGINE_KEY.get(key_code, key_code)


def event_character(event):
    """Get the keyboard-layout-aware text associated with a Quartz key event."""
    try:
        length, text = Quartz.CGEventKeyboardGetUnicodeString(event, 8, None, None)
        return str(text or "")[:1] if length else ""
    except Exception:
        return ""


def _is_our_event(event):
    return Quartz.CGEventGetIntegerValueField(event, Quartz.kCGEventSourceUserData) == MAGIC


def _post(event):
    Quartz.CGEventSetIntegerValueField(event, Quartz.kCGEventSourceUserData, MAGIC)
    Quartz.CGEventPost(Quartz.kCGHIDEventTap, event)


def send_key(key_code):
    _post(Quartz.CGEventCreateKeyboardEvent(None, key_code, True))
    _post(Quartz.CGEventCreateKeyboardEvent(None, key_code, False))


def send_text(text):
    for char in text:
        key_down = Quartz.CGEventCreateKeyboardEvent(None, 0, True)
        Quartz.CGEventKeyboardSetUnicodeString(key_down, len(char), char)
        _post(key_down)
        key_up = Quartz.CGEventCreateKeyboardEvent(None, 0, False)
        Quartz.CGEventKeyboardSetUnicodeString(key_up, len(char), char)
        _post(key_up)


def send_plan(plan):
    for _ in range(max(0, min(plan.backspaces, Typist.MAX_BACKSPACES))):
        send_key(MAC_BACKSPACE)
    if plan.text:
        send_text(plan.text)
    if plan.vk_after:
        send_key(ENGINE_TO_MAC_KEY.get(plan.vk_after, plan.vk_after))


def _set_hook_ok(value, needs_permission=False):
    global hook_ok, permission_required
    hook_ok = value
    permission_required = needs_permission
    threading.Thread(target=refresh_tray, daemon=True).start()


def _event_callback(_proxy, event_type, event, _refcon):
    global in_target
    try:
        if event_type in (Quartz.kCGEventTapDisabledByTimeout, Quartz.kCGEventTapDisabledByUserInput):
            if _event_tap:
                Quartz.CGEventTapEnable(_event_tap, True)
            return event

        key_code = int(Quartz.CGEventGetIntegerValueField(event, Quartz.kCGKeyboardEventKeycode))
        if _is_our_event(event):
            return event

        if event_type == Quartz.kCGEventKeyUp:
            if key_code in swallowed:
                swallowed.discard(key_code)
                return None
            return event
        if event_type != Quartz.kCGEventKeyDown:
            return event

        flags = Quartz.CGEventGetFlags(event)
        command_option = (
            flags & Quartz.kCGEventFlagMaskCommand and flags & Quartz.kCGEventFlagMaskAlternate
        )
        if command_option and key_code == MAC_KEY_F12:
            threading.Thread(target=quit_app, daemon=True).start()
            return None
        if command_option and key_code == MAC_KEY_F11:
            threading.Thread(target=toggle_enabled, daemon=True).start()
            return None

        if not enabled:
            leave_target()
            return event

        bundle_id, title = foreground_info()
        if not is_target(bundle_id, title):
            leave_target()
            return event
        if not in_target:
            typist.reset()
            in_target = True
            threading.Thread(target=refresh_tray, daemon=True).start()

        if key_code in swallowed:
            return None
        combo = bool(flags & (
            Quartz.kCGEventFlagMaskCommand |
            Quartz.kCGEventFlagMaskControl |
            Quartz.kCGEventFlagMaskAlternate
        ))
        plan = typist.process(normalize_key(key_code), event_character(event), combo)
        if plan is None:
            return event
        swallowed.add(key_code)
        send_plan(plan)
        return None
    except Exception as exc:
        # Never prevent a user from typing because this utility encountered an error.
        if DEBUG:
            print("keyboard callback error:", exc)
        return event


def hook_thread():
    global _event_tap, _event_source, _hook_run_loop
    if not _is_accessibility_trusted(prompt=True):
        _set_hook_ok(False, needs_permission=True)
        return

    mask = (1 << Quartz.kCGEventKeyDown) | (1 << Quartz.kCGEventKeyUp)
    tap = Quartz.CGEventTapCreate(
        Quartz.kCGSessionEventTap,
        Quartz.kCGHeadInsertEventTap,
        Quartz.kCGEventTapOptionDefault,
        mask,
        _event_callback,
        None,
    )
    if tap is None:
        _set_hook_ok(False, needs_permission=True)
        return

    run_loop = Quartz.CFRunLoopGetCurrent()
    source = Quartz.CFMachPortCreateRunLoopSource(None, tap, 0)
    _event_tap, _event_source, _hook_run_loop = tap, source, run_loop
    Quartz.CFRunLoopAddSource(run_loop, source, Quartz.kCFRunLoopDefaultMode)
    Quartz.CGEventTapEnable(tap, True)
    _set_hook_ok(True)
    Quartz.CFRunLoopRun()
    Quartz.CFRunLoopRemoveSource(run_loop, source, Quartz.kCFRunLoopDefaultMode)
    _event_tap, _event_source, _hook_run_loop = None, None, None
    _set_hook_ok(False)


def restart_hook(*_):
    if _event_tap:
        Quartz.CGEventTapEnable(_event_tap, True)
        _set_hook_ok(True)
    else:
        threading.Thread(target=hook_thread, daemon=True).start()


def quit_app(*_):
    if _hook_run_loop:
        Quartz.CFRunLoopStop(_hook_run_loop)
    if tray:
        tray.stop()


def build_menu():
    return pystray.Menu(
        pystray.MenuItem(status_text, lambda *_: None, enabled=False),
        pystray.Menu.SEPARATOR,
        pystray.MenuItem("Enabled", toggle_enabled, checked=lambda item: enabled, default=True),
        pystray.MenuItem("Capital at start of sentences", toggle_capitalize,
                         checked=lambda item: settings["capitalize"]),
        pystray.MenuItem("Fix words (let's, don't, I'm...)", toggle_fix_words,
                         checked=lambda item: settings["fix_words"]),
        pystray.Menu.SEPARATOR,
        pystray.MenuItem("Edit my corrections...", open_corrections),
        pystray.MenuItem("Open settings folder", open_data_folder),
        pystray.MenuItem("Open Accessibility settings", open_accessibility_settings),
        pystray.MenuItem("Restart keyboard listener", restart_hook),
        pystray.Menu.SEPARATOR,
        pystray.MenuItem("Quit", quit_app),
    )


def acquire_single_instance():
    global _lock_handle
    _lock_handle = open(LOCK_PATH, "a+", encoding="utf-8")
    try:
        fcntl.flock(_lock_handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        return True
    except BlockingIOError:
        _lock_handle.close()
        _lock_handle = None
        return False


def main():
    global tray, settings
    os.makedirs(DATA_DIR, exist_ok=True)
    if not acquire_single_instance():
        return

    autocorrect.set_folder(DATA_DIR)
    settings = settings_store.load(SETTINGS_PATH)
    typist.capitalize = settings["capitalize"]
    typist.fix_words = settings["fix_words"]

    threading.Thread(target=hook_thread, daemon=True).start()
    tray = pystray.Icon(APP_NAME, make_icon("error"), TRAY_TITLE, build_menu())

    def setup(icon):
        icon.visible = True
        refresh_tray()

    tray.run(setup)


if __name__ == "__main__":
    main()
